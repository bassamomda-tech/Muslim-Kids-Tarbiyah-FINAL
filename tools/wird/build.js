/* tools/wird/build.js — builds corners/shared/wird-data.js for «وِردي» (the daily Quran reading).
   Takes ONLY the verified Uthmani verse text of the 80 surahs already on the site
   (corners/quran-hifz/quran-data: al-Fatihah + surahs 36–114) — nothing is typed or changed here.
   Order = how children usually progress: al-Fatihah, Juz 'Amma (78→114), then juz 29, 28 … back to Ya-Sin.
   Run: node tools/wird/build.js */
const fs = require('fs'), path = require('path'), ROOT = path.resolve(__dirname, '../..'), QH = path.join(ROOT, 'corners/quran-hifz');
global.window = { SURAHS: {} };
require(path.join(QH, 'data/content.js'));
const C = window.QG.content;
for (const f of fs.readdirSync(path.join(QH, 'quran-data'))) if (f !== 'index_data.js') require(path.join(QH, 'quran-data', f));
const S = window.SURAHS, EN = { fatihah: 'Al-Fatihah' };
const rows = Object.keys(S).map(k => ({ k, n: k === 'fatihah' ? 1 : (C[k] || {}).num, name: k === 'fatihah' ? 'الفاتحة' : (C[k] || {}).name, ay: (S[k].verses || []).map(v => v.ar) })).filter(r => r.n && r.ay.length);
const JUZ = [[1, 1], [78, 114], [67, 77], [58, 66], [51, 57], [46, 50], [41, 45], [36, 40]];
const out = [];
for (const [a, b] of JUZ) rows.filter(r => r.n >= a && r.n <= b).sort((x, y) => x.n - y.n).forEach(r => out.push({ n: r.n, name: r.name, ay: r.ay }));
const total = out.reduce((s, r) => s + r.ay.length, 0);
fs.writeFileSync(path.join(ROOT, 'corners/shared/wird-data.js'),
  "/* wird-data.js — GENERATED by tools/wird/build.js from the site's verified Uthmani surah files. Do not edit by hand.\n   " + out.length + ' surahs, ' + total + " ayat, in wird order (al-Fatihah, Juz 'Amma, then back towards Ya-Sin). */\nwindow.MK_WIRD=" + JSON.stringify(out) + ';\n');
console.log(out.length, 'surahs', total, 'ayat', Math.round(fs.statSync(path.join(ROOT, 'corners/shared/wird-data.js')).size / 1024) + ' KB');
