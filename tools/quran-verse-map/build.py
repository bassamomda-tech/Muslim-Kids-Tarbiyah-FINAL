import json, re, os, sys, html, bisect, collections
QV = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(QV, 'data')
ROOT = os.path.abspath(os.path.join(QV, '..', '..'))
d = None
DIAC = re.compile('[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640\u08D3-\u08FF]')
def norm(s):
    s = DIAC.sub('', s)
    s = re.sub('[أإآٱ]', 'ا', s); s = s.replace('ى','ي').replace('ة','ه').replace('ؤ','و').replace('ئ','ي')
    s = re.sub('[^\u0621-\u064A]', '', s)       # Arabic letters only
    s = s.replace('ا','').replace('ء','')
    return s
big=[]; starts=[]; refs=[]; pos=0; WS=[]; SEG=[]
for c in range(1,115):
    sg=json.load(open(os.path.join(DATA,'seg/%d.json'%c)))
    for v in json.load(open(os.path.join(DATA,'words/%d.json'%c))):
        ws=[norm(w) for w in v['w']]; offs=[]; o=0
        for w in ws: offs.append(o); o+=len(w)
        n=''.join(ws); s_,a_=map(int,v['k'].split(':'))
        starts.append(pos); refs.append((s_,a_)); big.append(n); WS.append(offs); SEG.append({x[1]:(x[2],x[3]) for x in (sg.get(v['k']) or []) if len(x)>=4}); pos+=len(n)
BIG=''.join(big)
def ayah_at(p): return bisect.bisect_right(starts,p)-1
def match(n):
    i = BIG.find(n)
    if i>=0:
        a=ayah_at(i); b=ayah_at(i+len(n)-1)
        wa=bisect.bisect_right(WS[a],i-starts[a])   # 1-based word pos of first char
        wb=bisect.bisect_right(WS[b],i+len(n)-1-starts[b])
        return a,b,1.0,wa,wb
    # fuzzy: vote 6-gram chunks
    K=6; votes=collections.Counter()
    for j in range(0,len(n)-K+1,3):
        c=n[j:j+K]; k=BIG.find(c)
        hits=0
        while k>=0 and hits<40:
            votes[ayah_at(k)]+=1; hits+=1; k=BIG.find(c,k+1)
    if not votes: return None
    a,_=votes.most_common(1)[0]
    # expand over neighbours, score coverage
    best=None
    for lo in range(max(0,a-3),a+1):
        for hi in range(a,min(len(refs)-1,a+3)+1):
            seg=BIG[starts[lo]:starts[hi]+len(big[hi])]
            import difflib
            sm=difflib.SequenceMatcher(None,n,seg,autojunk=False)
            m=sum(x.size for x in sm.get_matching_blocks())
            cov=m/len(n); prec=m/len(seg)
            sc=cov*0.75+prec*0.25
            if cov>=0.8 and (best is None or sc>best[2]): best=(lo,hi,sc,1,len(WS[hi]))
    return best
def fnv(s):
    h=0x811c9dc5
    for ch in s.encode('utf-8'):
        h^=ch; h=(h*0x01000193)&0xffffffff
    return h
SNIP=re.compile('﴿(.*?)﴾', re.S)
files=[]
for dp,dn,fn in os.walk(ROOT):
    if any(x in dp for x in ('/node_modules','/.git','/uploads','/functions')): continue
    for f in fn:
        if f.endswith(('.js','.html')): files.append(os.path.join(dp,f))
out={}; miss=[]; stats=collections.Counter()
for f in files:
    try: txt=open(f,encoding='utf-8').read()
    except: continue
    for m in SNIP.finditer(txt):
        s=m.group(1)
        if len(s)>1500: continue
        s=re.sub(r'\\u([0-9a-fA-F]{4})',lambda x:chr(int(x.group(1),16)),s)
        s=re.sub(r'\\[nrt"\']',' ',s); s=re.sub('<[^>]*>','',s); s=html.unescape(s)
        n=norm(s)
        if len(n)<6: stats['short']+=1; continue
        h=fnv(n)
        if h in out or h in [x[0] for x in miss[-0:]]: stats['dup']+=1; continue
        r=match(n)
        if not r: miss.append((h,f,s[:80])); stats['miss']+=1; continue
        a,b,sc,wa,wb=r
        if b-a>12: miss.append((h,f,'RANGE '+s[:60])); stats['range']+=1; continue
        (s1,a1),(s2,a2)=refs[a],refs[b]
        ref = '%d:%d'%(s1,a1) if a==b else ('%d:%d-%d'%(s1,a1,a2) if s1==s2 else None)
        if not ref: stats['cross']+=1; continue
        t0=t1=None
        if wa>1:
            sg=SEG[a]; p=wa
            while p>1 and p not in sg: p-=1
            if p in sg and p>1: t0=max(0,sg[p][0]-60)
        if wb<len(WS[b]):
            sg=SEG[b]; p=wb
            while p<len(WS[b]) and p not in sg: p+=1
            if p in sg and p<len(WS[b]): t1=sg[p][1]+180
        if t0 is not None: ref+='@%d'%t0
        if t1 is not None: ref+='~%d'%t1
        out[h]=ref; stats['fuzzy' if sc<1 else 'exact']+=1
print(stats, len(out))
json.dump({'map':{format(k,'x'):v for k,v in out.items()},'miss':miss},open(os.path.join(DATA,'map.json'),'w'),ensure_ascii=False)

m = out
body = ','.join('"%x":"%s"' % (k, v) for k, v in sorted(m.items()))
