/* build.js — regenerate corners/shared/quran-verse-map.js (the fast, built-in list of the site's
   Quran quotes). Uses the SAME matcher as the voice server (functions/quran-match.js).
   Run from the repo root after adding many new verses (optional: the server also recognises
   new verses by itself):   node tools/quran-verse-map/build.js */
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const q = require(path.join(ROOT, 'functions', 'quran-match.js'));
function hash(n) { const b = Buffer.from(n, 'utf8'); let x = 0x811c9dc5; for (const c of b) { x ^= c; x = Math.imul(x, 0x01000193); } return (x >>> 0).toString(16); }
const files = [];
(function walk(d) { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (/(^|\/)(uploads|node_modules|\.git|functions|tools)(\/|$)/.test(path.relative(ROOT, p))) continue; const st = fs.statSync(p); if (st.isDirectory()) walk(p); else if (/\.(js|html)$/.test(f) && !/quran-verse-map\.js$/.test(f)) files.push(p); } })(ROOT);
const map = {}; let miss = 0;
for (const f of files) {
  const t = fs.readFileSync(f, 'utf8');
  for (const m of t.matchAll(/﴿([\s\S]*?)﴾/g)) {
    let s = m[1]; if (s.length > 1500) continue;
    s = s.replace(/\\u([0-9a-fA-F]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16))).replace(/\\[nrt"']/g, ' ').replace(/<[^>]*>/g, '').replace(/&nbsp;/g, ' ');
    const n = q.norm(s); if (n.length < 6) continue;
    const k = hash(n); if (k in map) continue;
    const r = q.match(s); if (r) map[k] = r; else miss++;
  }
}
const body = Object.keys(map).sort().map((k) => `"${k}":"${map[k]}"`).join(',');
fs.writeFileSync(path.join(ROOT, 'corners', 'shared', 'quran-verse-map.js'),
  "/* quran-verse-map.js — GENERATED by tools/quran-verse-map/build.js. Do not edit by hand.\n" +
  " Every Quran quote written between ﴿ ﴾ on the site → its place in the mushaf, so read-aloud plays\n" +
  " Sheikh Mahmoud Khalil Al-Husary's real recitation instead of a computer voice. Quotes added later\n" +
  " are also recognised by the voice server (functions/quran-match.js); this list just makes it instant.\n" +
  " key = FNV-1a hash of the quote's bare letters; value = surah:ayah[-ayah][@startMs][~endMs] */\n" +
  'window.MK_QV_MAP={' + body + '};\n');
console.log('quotes mapped:', Object.keys(map).length, '· not Quran / not found:', miss);
